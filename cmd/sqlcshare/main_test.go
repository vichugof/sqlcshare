package main

import (
	"bytes"
	"os"
	osexec "os/exec"
	"path/filepath"
	"strings"
	"testing"
)

func TestRun(t *testing.T) {
	root := t.TempDir()
	src := filepath.Join("..", "..", "testdata", "golden", "postgresql")
	for _, sub := range []string{"fragments", "queries", "schema"} {
		if err := os.CopyFS(filepath.Join(root, sub), os.DirFS(filepath.Join(src, sub))); err != nil {
			t.Fatal(err)
		}
	}
	var stdout, stderr bytes.Buffer
	exec := func(args ...string) int {
		stdout.Reset()
		stderr.Reset()
		return run(args, &stdout, &stderr)
	}
	if code := exec("expand", "-engine", "postgresql", "-root", root, "-fragments", "fragments", "-sources", "queries", "-out", "gen/sql", "-v"); code != 0 {
		t.Fatalf("expand: exit %d\n%s%s", code, stdout.String(), stderr.String())
	}
	if !strings.Contains(stdout.String(), "wrote gen/sql/authors.sql") {
		t.Errorf("verbose output: %s", stdout.String())
	}
	if code := exec("expand", "-engine", "postgresql", "-root", root, "-fragments", "fragments", "-sources", "queries", "-out", "gen/sql", "-check"); code != 0 {
		t.Errorf("check after expand: exit %d\n%s%s", code, stdout.String(), stderr.String())
	}
	cfg := `version: "2"
options:
  sqlcshare:
    fragments: fragments
    sources: queries
    out: gen/sql
sql:
  - engine: postgresql
    schema: schema
    queries: gen/sql
    gen:
      go:
        package: db
        out: db
`
	if err := os.WriteFile(filepath.Join(root, "sqlc.yaml"), []byte(cfg), 0o644); err != nil {
		t.Fatal(err)
	}
	f, err := os.OpenFile(filepath.Join(root, "queries", "orgs.sql"), os.O_APPEND|os.O_WRONLY, 0)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := f.WriteString("\n-- name: CountOrgs :one\nSELECT count(*) FROM orgs;\n"); err != nil {
		t.Fatal(err)
	}
	f.Close()
	if code := exec("generate", "-f", filepath.Join(root, "sqlc.yaml"), "-check"); code != 1 || !strings.Contains(stdout.String(), "out of date: gen/sql/orgs.sql") {
		t.Errorf("generate -check should report drift: exit %d\n%s%s", code, stdout.String(), stderr.String())
	}
	if code := exec("generate", "-f", filepath.Join(root, "sqlc.yaml"), "-no-sqlc"); code != 0 {
		t.Errorf("generate -no-sqlc: exit %d\n%s%s", code, stdout.String(), stderr.String())
	}
	if code := exec("generate", "-f", filepath.Join(root, "sqlc.yaml"), "-sqlc", "definitely-not-a-command-xyz"); code != 1 || !strings.Contains(stderr.String(), "running definitely-not-a-command-xyz") {
		t.Errorf("missing sqlc binary: exit %d\n%s", code, stderr.String())
	}
	if code := exec("expand", "-engine", "nope"); code != 2 {
		t.Errorf("bad engine: exit %d", code)
	}
	if code := exec("expand", "-engine", "postgresql", "-validate", "bogus", "-root", root, "-sources", "queries", "-out", "gen/sql"); code != 2 || !strings.Contains(stderr.String(), "-validate must be") {
		t.Errorf("bad -validate: exit %d %s", code, stderr.String())
	}
	if code := exec("expand", "-engine", "postgresql", "-validate", "off", "-root", root, "-fragments", "fragments", "-sources", "queries", "-out", "gen/sql", "-check"); code != 0 {
		t.Errorf("-validate off: exit %d\n%s%s", code, stdout.String(), stderr.String())
	}
	// A broken fragment is caught by the built-in parsers before sqlc runs.
	if err := os.WriteFile(filepath.Join(root, "fragments", "broken.sql"), []byte("-- fragment: broken(a) :where\n{a}.x = 1 AND;\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if code := exec("generate", "-f", filepath.Join(root, "sqlc.yaml"), "-no-sqlc"); code != 1 || !strings.Contains(stderr.String(), `fragments/broken.sql:2:`) || !strings.Contains(stderr.String(), `fragment "broken": syntax error`) {
		t.Errorf("broken fragment: exit %d\n%s", code, stderr.String())
	}
	os.Remove(filepath.Join(root, "fragments", "broken.sql"))
	// The Go side needs sqlc's output: without it, gocode says so.
	if code := exec("gocode", "-f", filepath.Join(root, "sqlc.yaml")); code != 1 || !strings.Contains(stderr.String(), "run sqlc generate first") {
		t.Errorf("gocode without sqlc output: exit %d\n%s", code, stderr.String())
	}
	if _, err := osexec.LookPath("sqlc"); err == nil {
		goFile := filepath.Join(root, "db", "sqlcshare.go")
		if code := exec("generate", "-f", filepath.Join(root, "sqlc.yaml"), "-v"); code != 0 || !strings.Contains(stdout.String(), "wrote db/sqlcshare.go") {
			t.Fatalf("generate with sqlc: exit %d\n%s%s", code, stdout.String(), stderr.String())
		}
		if code := exec("generate", "-f", filepath.Join(root, "sqlc.yaml"), "-check"); code != 0 {
			t.Errorf("check after generate: exit %d\n%s%s", code, stdout.String(), stderr.String())
		}
		if code := exec("gocode", "-f", filepath.Join(root, "sqlc.yaml"), "-check", "-v"); code != 0 || !strings.Contains(stdout.String(), "unchanged db/sqlcshare.go") {
			t.Errorf("gocode -check: exit %d\n%s%s", code, stdout.String(), stderr.String())
		}
		if err := os.WriteFile(goFile, []byte("// Code generated by sqlcshare. DO NOT EDIT.\n\npackage db\n"), 0o644); err != nil {
			t.Fatal(err)
		}
		if code := exec("generate", "-f", filepath.Join(root, "sqlc.yaml"), "-check"); code != 1 || !strings.Contains(stdout.String(), "out of date: db/sqlcshare.go") {
			t.Errorf("check must see a stale sqlcshare.go: exit %d\n%s%s", code, stdout.String(), stderr.String())
		}
		if code := exec("gocode", "-f", filepath.Join(root, "sqlc.yaml"), "-v"); code != 0 || !strings.Contains(stdout.String(), "wrote db/sqlcshare.go") {
			t.Errorf("gocode: exit %d\n%s%s", code, stdout.String(), stderr.String())
		}
		if code := exec("generate", "-f", filepath.Join(root, "sqlc.yaml"), "-no-go", "-v"); code != 0 || strings.Contains(stdout.String(), "sqlcshare.go") {
			t.Errorf("-no-go must leave the Go side alone: exit %d\n%s%s", code, stdout.String(), stderr.String())
		}
	}
	if code := exec("bogus"); code != 2 {
		t.Errorf("unknown command: exit %d", code)
	}
	if code := exec("version"); code != 0 || !strings.HasPrefix(stdout.String(), "sqlcshare ") {
		t.Errorf("version: exit %d %q", code, stdout.String())
	}
	if code := exec(); code != 2 {
		t.Errorf("no args: exit %d", code)
	}
}
