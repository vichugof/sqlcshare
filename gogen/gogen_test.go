// fakeSqlcOutput mimics what sqlc writes for the statements below under
// database/sql: a parameter struct for every query with two or more
// parameters, a bare argument otherwise.
const fakeSqlcOutput = `// Code generated by sqlc. DO NOT EDIT.

package db

import (
	"context"
	"database/sql"
	"time"
)

type DBTX interface{}

type Queries struct{ db DBTX }

type ListAuthorsParams struct {
	OrgID   int64
	Since   sql.NullTime
	Pattern string
	Limit   int32
}

func (q *Queries) ListAuthors(ctx context.Context, arg ListAuthorsParams) ([]int64, error) { return nil, nil }

type CountListAuthorsParams struct {
	OrgID   int64
	Since   sql.NullTime
	Pattern string
}

func (q *Queries) CountListAuthors(ctx context.Context, arg CountListAuthorsParams) (int64, error) { return 0, nil }

type GetAuthorParams struct {
	OrgID int64
	Since sql.NullTime
	ID    int64
}

func (q *Queries) GetAuthor(ctx context.Context, arg GetAuthorParams) (int64, error) { return 0, nil }

func (q *Queries) CountAuthors(ctx context.Context, orgID int64) (int64, error) { return 0, nil }

type ListByTimeParams struct {
	OrgID int64
	Since time.Time
	Until time.Time
}

func (q *Queries) ListByTime(ctx context.Context, arg ListByTimeParams) ([]int64, error) { return nil, nil }
`

const fragments = `-- fragment: visible(a) :where
{a}.deleted_at IS NULL AND {a}.org_id = sqlc.arg(org_id) AND {a}.created_at > sqlc.narg(since);

-- fragment: cols(a) :columns
{a}.id;

-- fragment: window(a) :where
{a}.created_at > sqlc.arg(since) AND {a}.created_at < sqlc.arg(until);
`

const sources = `-- name: ListAuthors :many
-- derive: CountListAuthors :count
SELECT /*%columns cols(a)*/ a.id /*%end*/ FROM authors a
WHERE /*%where visible(a)*/ TRUE /*%end*/ AND a.name LIKE sqlc.arg(pattern)
ORDER BY a.id LIMIT sqlc.arg(limit);

-- name: GetAuthor :one
SELECT a.id FROM authors a WHERE /*%where visible(a)*/ TRUE /*%end*/ AND a.id = sqlc.arg(id);

-- name: CountAuthors :one
SELECT count(*) FROM authors a WHERE a.org_id = sqlc.arg(org_id);

-- name: ListByTime :many
SELECT a.id FROM authors a WHERE a.org_id = sqlc.arg(org_id) AND /*%where window(a)*/ TRUE /*%end*/;
`

func statements(t *testing.T, engine sqlcshare.Engine, frags, srcs string) []sqlcshare.Statement {
	t.Helper()
	fsys := fstest.MapFS{"f.sql": {Data: []byte(frags)}, "q.sql": {Data: []byte(srcs)}}
	lib, diags := sqlcshare.Load(engine, fsys, "f.sql")
	if diags.HasErrors() {
		t.Fatal(diags)
	}
	res, err := (&sqlcshare.Expander{Engine: engine, Lib: lib}).Expand("queries/q.sql", []byte(srcs))
	if err != nil {
		t.Fatal(err)
	}
	return res.Statements
}

func TestGenerate(t *testing.T) {
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "query.sql.go"), []byte(fakeSqlcOutput), 0o644); err != nil {
		t.Fatal(err)
	}
	pkg := Package{Dir: dir, Statements: statements(t, sqlcshare.PostgreSQL, fragments, sources)}
	res, err := Generate(pkg, false)
	if err != nil {
		t.Fatalf("generate: %v\n%s", err, res.Text)
	}
	if !res.Changed {
		t.Error("first run must report a change")
	}
	got := string(res.Text)
	for _, want := range []string{
		"// Code generated by sqlcshare. DO NOT EDIT.\n\npackage db\n\nimport (\n\t\"database/sql\"\n\t\"time\"\n)\n",
		"// VisibleParams holds the parameters that fragment visible (f.sql:1:1) binds.\n// It is shared by CountListAuthors, GetAuthor and ListAuthors.\ntype VisibleParams struct {\n\tOrgID int64\n\tSince sql.NullTime\n}\n",
		"func (p GetAuthorParams) VisibleParams() VisibleParams {\n\treturn VisibleParams{OrgID: p.OrgID, Since: p.Since}\n}\n",
		"func (p GetAuthorParams) WithVisibleParams(f VisibleParams) GetAuthorParams {\n\tp.OrgID = f.OrgID\n\tp.Since = f.Since\n\treturn p\n}\n",
		"func (p ListAuthorsParams) VisibleParams() VisibleParams {",
		"// CountListAuthorsParams returns the parameters of CountListAuthors, the count of ListAuthors, taken from p.\nfunc (p ListAuthorsParams) CountListAuthorsParams() CountListAuthorsParams {\n\treturn CountListAuthorsParams{OrgID: p.OrgID, Since: p.Since, Pattern: p.Pattern}\n}\n",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("output lacks:\n%s\n--- got\n%s", want, got)
		}
	}
	// cols binds no parameters and window's parameters are fields of a
	// single query, which is enough for a struct; CountAuthors has no
	// parameter struct and gets no methods.
	if strings.Contains(got, "ColsParams") || strings.Contains(got, "CountAuthorsParams") {
		t.Errorf("unexpected output:\n%s", got)
	}
	if !strings.Contains(got, "type WindowParams struct {\n\tSince time.Time\n\tUntil time.Time\n}") || !strings.Contains(got, "\t\"time\"\n") {
		t.Errorf("window struct or time import missing:\n%s", got)
	}
	if len(res.Diagnostics) != 0 {
		t.Errorf("diagnostics: %v", res.Diagnostics)
	}
	// The file is on disk, reruns are no-ops, and check mode sees no drift.
	if _, err := os.Stat(res.Path); err != nil {
		t.Fatal(err)
	}
	res, err = Generate(pkg, true)
	if err != nil || res.Changed {
		t.Errorf("check after generate: changed=%v err=%v", res.Changed, err)
	}
	compile(t, dir)

	// A fragment whose parameter is typed differently in two queries gets
	// no struct, with an info diagnostic, and nothing else changes.
	src2 := strings.Replace(fakeSqlcOutput, "type GetAuthorParams struct {\n\tOrgID int64", "type GetAuthorParams struct {\n\tOrgID int32", 1)
	if err := os.WriteFile(filepath.Join(dir, "query.sql.go"), []byte(src2), 0o644); err != nil {
		t.Fatal(err)
	}
	res, err = Generate(pkg, false)
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(res.Text), "VisibleParams") || !strings.Contains(string(res.Text), "WindowParams") {
		t.Errorf("mismatched types must drop only that struct:\n%s", res.Text)
	}
	if ds := res.Diagnostics; len(ds) != 1 || ds[0].Severity != sqlcshare.Info || !strings.Contains(ds[0].Message, `parameter "org_id" of fragment "visible" has type int64 in CountListAuthors but int32 in GetAuthor; no shared struct`) {
		t.Errorf("diagnostics: %v", ds)
	}
	compile(t, dir)

	// With no statements there is nothing to generate: the file goes away.
	res, err = Generate(Package{Dir: dir}, false)
	if err != nil || !res.Changed || res.Text != nil {
		t.Errorf("empty package: changed=%v text=%q err=%v", res.Changed, res.Text, err)
	}
	if _, err := os.Stat(res.Path); !os.IsNotExist(err) {
		t.Error("stale file must be removed")
	}
	res, err = Generate(Package{Dir: dir}, false)
	if err != nil || res.Changed {
		t.Errorf("nothing to do twice: changed=%v err=%v", res.Changed, err)
	}

	// A file that sqlcshare did not write is never touched.
	if err := os.WriteFile(res.Path, []byte("package db\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if _, err := Generate(pkg, false); err == nil || !strings.Contains(err.Error(), "was not written by sqlcshare") {
		t.Errorf("foreign file: %v", err)
	}
	if _, err := Generate(Package{Dir: filepath.Join(dir, "missing")}, false); err == nil || !strings.Contains(err.Error(), "run sqlc generate first") {
		t.Errorf("missing dir: %v", err)
	}
}

func TestGenerateNamesAndCollisions(t *testing.T) {
	dir := t.TempDir()
	src := `package db

import "time"

type ListParams struct {
	OrgID    int64
	UserID   int64
	Since    time.Time
	TheUrl   string
	PerPage  int32
}

func (p ListParams) WithFilterParams(f int) ListParams { return p }

type FilterParams struct{}
`
	if err := os.WriteFile(filepath.Join(dir, "q.sql.go"), []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}
	frags := "-- fragment: filter(a) :where\n{a}.org_id = @org_id AND {a}.user_id = @user_id AND {a}.the_url = @the_url AND {a}.created_at > @since;\n"
	srcs := "-- name: List :many\nSELECT 1 FROM t a WHERE /*%where filter(a)*/ TRUE /*%end*/ LIMIT sqlc.arg(page_size);\n"
	pkg := Package{Dir: dir, Rename: map[string]string{"page_size": "PerPage"}, Initialisms: []string{"id", "url"}, Statements: statements(t, sqlcshare.PostgreSQL, frags, srcs)}
	res, err := Generate(pkg, true)
	if err != nil {
		t.Fatal(err)
	}
	// the_url is TheUrl in the struct but the initialisms say TheURL: the
	// field is not found, and the fragment is reported.
	if res.Text != nil || len(res.Diagnostics) != 1 || !strings.Contains(res.Diagnostics[0].Message, `parameter "the_url" is not a field of ListParams (expected TheURL)`) {
		t.Errorf("text %q diagnostics %v", res.Text, res.Diagnostics)
	}
	pkg.Initialisms = nil
	res, err = Generate(pkg, true)
	if err != nil {
		t.Fatal(err)
	}
	// Now the fields are found, but FilterParams exists in the package.
	if res.Text != nil || len(res.Diagnostics) != 1 || res.Diagnostics[0].Severity != sqlcshare.Warning || !strings.Contains(res.Diagnostics[0].Message, "the shared struct FilterParams would collide") {
		t.Errorf("text %q diagnostics %v", res.Text, res.Diagnostics)
	}
	src = strings.Replace(src, "\ntype FilterParams struct{}\n", "", 1)
	if err := os.WriteFile(filepath.Join(dir, "q.sql.go"), []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}
	res, err = Generate(pkg, true)
	if err != nil {
		t.Fatal(err)
	}
	// The setter name is taken on ListParams, so no struct is written either.
	if res.Text != nil || len(res.Diagnostics) != 1 || !strings.Contains(res.Diagnostics[0].Message, "already has a field or method named FilterParams or WithFilterParams") {
		t.Errorf("text %q diagnostics %v", res.Text, res.Diagnostics)
	}
}

func TestStructName(t *testing.T) {
	inits := map[string]bool{"id": true}
	for _, tc := range []struct{ in, want string }{
		{"org_id", "OrgID"},
		{"id", "ID"},
		{"page_size", "PageSize"},
		{"since", "Since"},
		{"visible_author", "VisibleAuthor"},
		{"1st", "_1st"},
		{"a-b", "AB"},
		{"ident", "Ident"},
	} {
		if got := structName(tc.in, nil, inits); got != tc.want {
			t.Errorf("structName(%q) = %q, want %q", tc.in, got, tc.want)
		}
	}
	if got := structName("page_size", map[string]string{"page_size": "PerPage"}, inits); got != "PerPage" {
		t.Errorf("rename: %q", got)
	}
	for _, tc := range []struct{ in, want string }{
		{"database/sql", "sql"},
		{"github.com/jackc/pgx/v5/pgtype", "pgtype"},
		{"github.com/jackc/pgx/v5", "pgx"},
		{"gopkg.in/guregu/null.v4", "null"},
		{"github.com/go-sql-driver/mysql", "mysql"},
	} {
		if got := defaultName(tc.in); got != tc.want {
			t.Errorf("defaultName(%q) = %q, want %q", tc.in, got, tc.want)
		}
	}
}

// compile type-checks the package in dir as a module of its own.
func compile(t *testing.T, dir string) {
	t.Helper()
	gocmd, err := exec.LookPath("go")
	if err != nil {
		t.Skip("go not on PATH")
	}
	if err := os.WriteFile(filepath.Join(dir, "go.mod"), []byte("module fake\n\ngo 1.26\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	cmd := exec.Command(gocmd, "vet", ".")
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "GOFLAGS=-mod=mod", "GOWORK=off")
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("generated code does not compile: %v\n%s", err, out)
	}
}
