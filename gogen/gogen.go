// Package gogen writes Go code next to sqlc's output that ties queries
// together by the fragments they share: a parameter struct per fragment,
// conversion methods on the parameter structs sqlc generated, and, for every
// derived count query, a method that builds its parameters from those of the
// query it was derived from.
//
// It reads the package sqlc generated instead of mapping database types
// itself, so the Go types it uses are exactly the ones sqlc chose under the
// overrides and sql_package in effect. A fragment whose parameters sqlc typed
// differently in two queries, or that is used with different parameter
// names, gets no shared struct and is reported instead; what is generated
// compiles because every type is copied from a struct that already does.
//
// For a fragment visible_author that binds org_id and is used by ListAuthors
// and CountAuthors, both of which have a parameter struct, the output is
//
//	type VisibleAuthorParams struct {
//		OrgID int64
//	}
//
//	func (p ListAuthorsParams) VisibleAuthorParams() VisibleAuthorParams
//	func (p ListAuthorsParams) WithVisibleAuthorParams(f VisibleAuthorParams) ListAuthorsParams
//	func (p CountAuthorsParams) VisibleAuthorParams() VisibleAuthorParams
//	func (p CountAuthorsParams) WithVisibleAuthorParams(f VisibleAuthorParams) CountAuthorsParams
//
// and for `-- derive: CountAuthors :count` on ListAuthors,
//
//	func (p ListAuthorsParams) CountAuthorsParams() CountAuthorsParams
//
// A query that sqlc gave no parameter struct, because it has one parameter or
// query_parameter_limit allows several bare ones, gets no methods: its
// arguments are passed directly.
package gogen

import (
	"bytes"
	"errors"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"go/types"
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"unicode"
	"unicode/utf8"

	"github.com/vichugof/sqlcshare"
)

// FileName is the file written into the package directory.
const FileName = "sqlcshare.go"

// header is the first line of the generated file; a file without it is never
// overwritten or removed.
const header = "// Code generated by sqlcshare. DO NOT EDIT."

// Package is one Go package sqlc generated and the statements that were
// compiled into it.
type Package struct {
	// Dir is the directory sqlc wrote the package to (gen.go.out).
	Dir string
	// Rename and Initialisms are sqlc's gen.go.rename and gen.go.initialisms,
	// which decide the field names sqlc gave to parameters. A nil Initialisms
	// means sqlc's default, "id".
	Rename      map[string]string
	Initialisms []string
	// Statements are the statements of the expanded files the package was
	// compiled from, as Report.Files[i].Statements lists them.
	Statements []sqlcshare.Statement
}

// Result is the outcome of Generate.
type Result struct {
	Path string // the file, Dir/FileName
	// Text is the file's content, or nil when there is nothing to generate
	// and the file must not exist.
	Text []byte
	// Changed reports that the file on disk differed from Text, was missing,
	// or was stale and had to be removed.
	Changed     bool
	Diagnostics sqlcshare.Diagnostics
}

// Generate writes FileName into pkg.Dir, or removes it when nothing is to be
// generated. With check set nothing is written and Changed reports what
// would happen. The returned error is the Diagnostics when any has severity
// Error, or an I/O error.
func Generate(pkg Package, check bool) (*Result, error) {
	res := &Result{Path: filepath.Join(pkg.Dir, FileName)}
	gp, err := readPackage(pkg.Dir)
	if err != nil {
		return res, err
	}
	g := &generator{pkg: pkg, gp: gp, rename: pkg.Rename, initialisms: map[string]bool{}}
	inits := pkg.Initialisms
	if inits == nil {
		inits = []string{"id"}
	}
	for _, s := range inits {
		g.initialisms[s] = true
	}
	res.Text = g.generate()
	res.Diagnostics = g.diags
	sort.SliceStable(res.Diagnostics, func(i, j int) bool { return res.Diagnostics[i].Message < res.Diagnostics[j].Message })
	if res.Diagnostics.HasErrors() {
		return res, res.Diagnostics
	}
	cur, err := os.ReadFile(res.Path)
	switch {
	case errors.Is(err, fs.ErrNotExist):
		cur = nil
	case err != nil:
		return res, err
	case !bytes.HasPrefix(cur, []byte(header)):
		return res, fmt.Errorf("gogen: %s exists and was not written by sqlcshare; move it away", res.Path)
	}
	if bytes.Equal(cur, res.Text) {
		return res, nil
	}
	res.Changed = true
	if check {
		return res, nil
	}
	if res.Text == nil {
		if err := os.Remove(res.Path); err != nil && !errors.Is(err, fs.ErrNotExist) {
			return res, err
		}
		return res, nil
	}
	return res, os.WriteFile(res.Path, res.Text, 0o644)
}

// goPackage is what Generate needs to know about the package sqlc wrote.
type goPackage struct {
	name    string
	idents  map[string]bool            // top-level identifiers
	structs map[string]*goStruct       // by type name
	methods map[string]map[string]bool // receiver base type -> method names
}

type goStruct struct {
	fields  []goField
	byName  map[string]*goField
	imports map[string]string // of the file that declares the struct: identifier -> path
}

type goField struct {
	name string
	typ  ast.Expr
}

// readPackage parses the Go files in dir, leaving out tests, the generated
// file itself, and files of another package.
func readPackage(dir string) (*goPackage, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, fmt.Errorf("gogen: %v (run sqlc generate first)", err)
	}
	gp := &goPackage{idents: map[string]bool{}, structs: map[string]*goStruct{}, methods: map[string]map[string]bool{}}
	fset := token.NewFileSet()
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") || name == FileName {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(dir, name), nil, parser.SkipObjectResolution)
		if err != nil {
			return nil, fmt.Errorf("gogen: %v", err)
		}
		if gp.name == "" {
			gp.name = f.Name.Name
		} else if f.Name.Name != gp.name {
			continue
		}
		imports := map[string]string{}
		for _, im := range f.Imports {
			p, err := strconv.Unquote(im.Path.Value)
			if err != nil {
				continue
			}
			ident := defaultName(p)
			if im.Name != nil {
				ident = im.Name.Name
			}
			imports[ident] = p
		}
		for _, decl := range f.Decls {
			switch d := decl.(type) {
			case *ast.FuncDecl:
				if d.Recv == nil || len(d.Recv.List) == 0 {
					gp.idents[d.Name.Name] = true
					continue
				}
				recv := receiverName(d.Recv.List[0].Type)
				if gp.methods[recv] == nil {
					gp.methods[recv] = map[string]bool{}
				}
				gp.methods[recv][d.Name.Name] = true
			case *ast.GenDecl:
				for _, spec := range d.Specs {
					switch s := spec.(type) {
					case *ast.TypeSpec:
						gp.idents[s.Name.Name] = true
						if st, ok := s.Type.(*ast.StructType); ok {
							gp.structs[s.Name.Name] = newStruct(st, imports)
						}
					case *ast.ValueSpec:
						for _, n := range s.Names {
							gp.idents[n.Name] = true
						}
					}
				}
			}
		}
	}
	if gp.name == "" {
		return nil, fmt.Errorf("gogen: no Go files in %s (run sqlc generate first)", dir)
	}
	return gp, nil
}

func newStruct(st *ast.StructType, imports map[string]string) *goStruct {
	s := &goStruct{byName: map[string]*goField{}, imports: imports}
	for _, f := range st.Fields.List {
		for _, n := range f.Names {
			s.fields = append(s.fields, goField{name: n.Name, typ: f.Type})
		}
	}
	for i := range s.fields {
		s.byName[s.fields[i].name] = &s.fields[i]
	}
	return s
}

func receiverName(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.StarExpr:
		return receiverName(t.X)
	case *ast.Ident:
		return t.Name
	case *ast.IndexExpr:
		return receiverName(t.X)
	case *ast.IndexListExpr:
		return receiverName(t.X)
	}
	return ""
}

// defaultName returns the identifier an unaliased import of p binds, as far
// as the path tells: its last element, less a major version suffix.
func defaultName(p string) string {
	base := path.Base(p)
	if len(base) > 1 && base[0] == 'v' && strings.Trim(base[1:], "0123456789") == "" {
		base = path.Base(path.Dir(p))
	}
	if i := strings.Index(base, ".v"); i > 0 && strings.Trim(base[i+2:], "0123456789") == "" {
		base = base[:i]
	}
	return strings.ReplaceAll(base, "-", "")
}

// typeKey renders a type so that two renderings are equal exactly when the
// types are: package selectors are replaced by the import path they resolve
// to in the declaring file.
func typeKey(e ast.Expr, imports map[string]string) string {
	switch t := e.(type) {
	case *ast.Ident:
		return t.Name
	case *ast.SelectorExpr:
		if x, ok := t.X.(*ast.Ident); ok {
			if p, ok := imports[x.Name]; ok {
				return strconv.Quote(p) + "." + t.Sel.Name
			}
			return x.Name + "." + t.Sel.Name
		}
	case *ast.StarExpr:
		return "*" + typeKey(t.X, imports)
	case *ast.ArrayType:
		if t.Len == nil {
			return "[]" + typeKey(t.Elt, imports)
		}
		return "[" + types.ExprString(t.Len) + "]" + typeKey(t.Elt, imports)
	case *ast.MapType:
		return "map[" + typeKey(t.Key, imports) + "]" + typeKey(t.Value, imports)
	case *ast.InterfaceType:
		if t.Methods == nil || len(t.Methods.List) == 0 {
			return "interface{}"
		}
	}
	return types.ExprString(e)
}

// selectors lists the package identifiers a type expression refers to.
func selectors(e ast.Expr) []string {
	var out []string
	ast.Inspect(e, func(n ast.Node) bool {
		if s, ok := n.(*ast.SelectorExpr); ok {
			if x, ok := s.X.(*ast.Ident); ok {
				out = append(out, x.Name)
			}
		}
		return true
	})
	return out
}

// structName is sqlc's StructName: how a column or parameter name becomes a
// Go field or type name.
func structName(name string, rename map[string]string, initialisms map[string]bool) string {
	if r := rename[name]; r != "" {
		return r
	}
	name = strings.Map(func(r rune) rune {
		if unicode.IsLetter(r) || unicode.IsDigit(r) {
			return r
		}
		return '_'
	}, name)
	var out strings.Builder
	for _, p := range strings.Split(name, "_") {
		if initialisms[p] {
			out.WriteString(strings.ToUpper(p))
		} else if p != "" {
			r, size := utf8.DecodeRuneInString(p)
			out.WriteString(string(unicode.ToUpper(r)) + p[size:])
		}
	}
	s := out.String()
	if r, _ := utf8.DecodeRuneInString(s); unicode.IsDigit(r) {
		return "_" + s
	}
	return s
}

type generator struct {
	pkg         Package
	gp          *goPackage
	rename      map[string]string
	initialisms map[string]bool
	diags       sqlcshare.Diagnostics
	imports     map[string]string // identifier -> path, for the generated file
	generated   map[string]bool   // type names written
	body        bytes.Buffer
}

func (g *generator) info(format string, args ...any) {
	g.diags = append(g.diags, sqlcshare.Diagnostic{Severity: sqlcshare.Info, Message: fmt.Sprintf(format, args...)})
}

func (g *generator) warn(format string, args ...any) {
	g.diags = append(g.diags, sqlcshare.Diagnostic{Severity: sqlcshare.Warning, Message: fmt.Sprintf(format, args...)})
}

// query is a named statement and the parameter struct sqlc gave it, if any.
type query struct {
	stmt   sqlcshare.Statement
	params *goStruct // nil when the query has no XxxParams struct
	name   string    // the struct's name
}

// fragUse is one use of a fragment in a query.
type fragUse struct {
	q   *query
	use sqlcshare.Use
}

// generate returns the file content, or nil when nothing is to be written.
func (g *generator) generate() []byte {
	g.imports = map[string]string{}
	g.generated = map[string]bool{}
	queries := map[string]*query{}
	var order []string
	byFrag := map[string][]fragUse{}
	for _, st := range g.pkg.Statements {
		if st.Name == "" || queries[st.Name] != nil {
			continue
		}
		q := &query{stmt: st, name: st.Name + "Params"}
		q.params = g.gp.structs[q.name]
		queries[st.Name] = q
		order = append(order, st.Name)
		for _, u := range st.Uses {
			byFrag[u.Name] = append(byFrag[u.Name], fragUse{q: q, use: u})
		}
	}
	frags := make([]string, 0, len(byFrag))
	for name := range byFrag {
		frags = append(frags, name)
	}
	sort.Strings(frags)
	for _, name := range frags {
		g.fragmentStruct(name, byFrag[name])
	}
	sort.Strings(order)
	for _, name := range order {
		q := queries[name]
		if q.stmt.Derived == sqlcshare.DeriveNone {
			continue
		}
		g.derivedParams(q, queries[q.stmt.DerivedFrom])
	}
	if g.body.Len() == 0 {
		return nil
	}
	var out bytes.Buffer
	out.WriteString(header + "\n\npackage " + g.gp.name + "\n\n")
	if len(g.imports) > 0 {
		paths := make([]string, 0, len(g.imports))
		byPath := map[string]string{}
		for ident, p := range g.imports {
			paths = append(paths, p)
			byPath[p] = ident
		}
		sort.Strings(paths)
		out.WriteString("import (\n")
		for _, p := range paths {
			if ident := byPath[p]; ident != defaultName(p) {
				out.WriteString("\t" + ident + " " + strconv.Quote(p) + "\n")
			} else {
				out.WriteString("\t" + strconv.Quote(p) + "\n")
			}
		}
		out.WriteString(")\n\n")
	}
	out.Write(g.body.Bytes())
	src, err := format.Source(out.Bytes())
	if err != nil {
		g.diags = append(g.diags, sqlcshare.Diagnostic{Severity: sqlcshare.Error, Message: "gogen: generated code does not format: " + err.Error()})
		return out.Bytes()
	}
	return src
}

// fragmentStruct writes the shared struct of one fragment and the conversion
// methods of the queries that use it.
func (g *generator) fragmentStruct(name string, uses []fragUse) {
	params := uses[0].use.Params
	for _, fu := range uses {
		if fu.use.Positional {
			g.info("fragment %q binds a positional placeholder in %s; no shared struct", name, fu.q.stmt.Name)
			return
		}
		if !sameSet(params, fu.use.Params) {
			g.info("fragment %q binds %s in %s but %s in %s; no shared struct", name, list(params), uses[0].q.stmt.Name, list(fu.use.Params), fu.q.stmt.Name)
			return
		}
	}
	if len(params) == 0 {
		return
	}
	var qs []*query
	seen := map[string]bool{}
	for _, fu := range uses {
		if fu.q.params != nil && !seen[fu.q.stmt.Name] {
			seen[fu.q.stmt.Name] = true
			qs = append(qs, fu.q)
		}
	}
	if len(qs) == 0 {
		return
	}
	sort.Slice(qs, func(i, j int) bool { return qs[i].stmt.Name < qs[j].stmt.Name })
	type field struct {
		param, name string
		typ         ast.Expr
		key         string
	}
	fields := make([]field, len(params))
	for i, p := range params {
		fields[i] = field{param: p, name: structName(p, g.rename, g.initialisms)}
	}
	for _, q := range qs {
		for i := range fields {
			f := q.params.byName[fields[i].name]
			if f == nil {
				g.info("fragment %q: parameter %q is not a field of %s (expected %s); no shared struct", name, fields[i].param, q.name, fields[i].name)
				return
			}
			key := typeKey(f.typ, q.params.imports)
			if fields[i].typ == nil {
				fields[i].typ, fields[i].key = f.typ, key
			} else if key != fields[i].key {
				g.info("parameter %q of fragment %q has type %s in %s but %s in %s; no shared struct", fields[i].param, name, types.ExprString(fields[i].typ), qs[0].stmt.Name, types.ExprString(f.typ), q.stmt.Name)
				return
			}
		}
	}
	typeName := structName(name, nil, g.initialisms) + "Params"
	if g.gp.idents[typeName] || g.generated[typeName] {
		g.warn("fragment %q: the shared struct %s would collide with an existing identifier; skipped", name, typeName)
		return
	}
	getter, setter := typeName, "With"+typeName
	var methodQs []*query
	for _, q := range qs {
		if q.params.byName[getter] != nil || q.params.byName[setter] != nil || g.gp.methods[q.name][getter] || g.gp.methods[q.name][setter] {
			g.warn("fragment %q: %s already has a field or method named %s or %s; no conversion methods for %s", name, q.name, getter, setter, q.stmt.Name)
			continue
		}
		methodQs = append(methodQs, q)
	}
	if len(methodQs) == 0 {
		return
	}
	for _, f := range fields {
		if !g.addImports(f.typ, qs[0].params.imports, name) {
			return
		}
	}
	g.generated[typeName] = true
	var names []string
	for _, q := range methodQs {
		names = append(names, q.stmt.Name)
	}
	def := uses[0].use.Def.String()
	fmt.Fprintf(&g.body, "// %s holds the parameters that fragment %s", typeName, name)
	if def != "" {
		fmt.Fprintf(&g.body, " (%s)", def)
	}
	fmt.Fprintf(&g.body, " binds.\n// It is shared by %s.\ntype %s struct {\n", prose(names), typeName)
	for _, f := range fields {
		fmt.Fprintf(&g.body, "\t%s %s\n", f.name, types.ExprString(f.typ))
	}
	g.body.WriteString("}\n\n")
	for _, q := range methodQs {
		fmt.Fprintf(&g.body, "// %s returns the parameters of fragment %s taken from p.\nfunc (p %s) %s() %s {\n\treturn %s{", getter, name, q.name, getter, typeName, typeName)
		for i, f := range fields {
			if i > 0 {
				g.body.WriteString(", ")
			}
			fmt.Fprintf(&g.body, "%s: p.%s", f.name, f.name)
		}
		g.body.WriteString("}\n}\n\n")
		fmt.Fprintf(&g.body, "// %s returns p with the parameters of fragment %s set from f.\nfunc (p %s) %s(f %s) %s {\n", setter, name, q.name, setter, typeName, q.name)
		for _, f := range fields {
			fmt.Fprintf(&g.body, "\tp.%s = f.%s\n", f.name, f.name)
		}
		g.body.WriteString("\treturn p\n}\n\n")
	}
}

// derivedParams writes the method that builds the parameters of a derived
// query from those of the query it came from.
func (g *generator) derivedParams(c, from *query) {
	if from == nil || c.params == nil || from.params == nil {
		return
	}
	method := c.name
	if from.params.byName[method] != nil || g.gp.methods[from.name][method] {
		g.warn("derived query %s: %s already has a field or method named %s; no conversion method", c.stmt.Name, from.name, method)
		return
	}
	for _, f := range c.params.fields {
		src := from.params.byName[f.name]
		if src == nil {
			g.info("derived query %s: parameter %s is not a parameter of %s; no conversion method", c.stmt.Name, f.name, from.stmt.Name)
			return
		}
		if typeKey(src.typ, from.params.imports) != typeKey(f.typ, c.params.imports) {
			g.info("derived query %s: parameter %s has type %s but %s in %s; no conversion method", c.stmt.Name, f.name, types.ExprString(f.typ), types.ExprString(src.typ), from.stmt.Name)
			return
		}
	}
	fmt.Fprintf(&g.body, "// %s returns the parameters of %s, the %s of %s, taken from p.\nfunc (p %s) %s() %s {\n\treturn %s{", method, c.stmt.Name, c.stmt.Derived, from.stmt.Name, from.name, method, c.name, c.name)
	for i, f := range c.params.fields {
		if i > 0 {
			g.body.WriteString(", ")
		}
		fmt.Fprintf(&g.body, "%s: p.%s", f.name, f.name)
	}
	g.body.WriteString("}\n}\n\n")
}

// addImports records the imports a type expression needs. It returns false,
// after a warning, when an identifier is already bound to another path.
func (g *generator) addImports(typ ast.Expr, imports map[string]string, frag string) bool {
	for _, ident := range selectors(typ) {
		p, ok := imports[ident]
		if !ok {
			continue
		}
		if prev, ok := g.imports[ident]; ok && prev != p {
			g.warn("fragment %q: type %s needs %s as %q but the generated file already imports it as %q; skipped", frag, types.ExprString(typ), ident, p, prev)
			return false
		}
		g.imports[ident] = p
	}
	return true
}

func sameSet(a, b []string) bool {
	if len(a) != len(b) {
		return false
	}
	as, bs := append([]string(nil), a...), append([]string(nil), b...)
	sort.Strings(as)
	sort.Strings(bs)
	for i := range as {
		if as[i] != bs[i] {
			return false
		}
	}
	return true
}

func list(names []string) string {
	if len(names) == 0 {
		return "no parameters"
	}
	return strings.Join(names, ", ")
}

// prose joins names as "A", "A and B" or "A, B and C".
func prose(names []string) string {
	switch len(names) {
	case 0:
		return ""
	case 1:
		return names[0]
	}
	return strings.Join(names[:len(names)-1], ", ") + " and " + names[len(names)-1]
}
